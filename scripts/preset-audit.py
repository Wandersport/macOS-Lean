#!/usr/bin/env python3
"""Read-only heuristics for review of a mac-os-debloat custom preset.

Does not connect to GitHub, require sudo, alter files, or claim safety.
EXIT 0 = no known critical label matched; it is NOT a security endorsement.
EXIT 1 = known critical match; EXIT 2 = usage/input problem.
"""
import argparse
import re
from pathlib import Path

CRITICAL = {
    "com.apple.perfpowermetricd": "native charge-limit and power metrics",
    "com.apple.powerlogHelperd": "native charge limiting",
    "com.apple.softwareupdated": "system security updates",
    "com.apple.XprotectService": "malware protection",
    "com.apple.syspolicyd": "application security policy",
    "com.apple.trustd": "system trust evaluation",
    "com.apple.securityd": "keychain and security",
    "com.apple.accountsd": "system account authentication",
    "com.apple.akd": "Apple ID authentication",
    "com.apple.appleaccountd": "Apple Account features",
    "com.apple.identityservicesd": "identity and account services",
    "com.apple.campo": "macOS 27 launcher / Spotlight overlay",
    "com.apple.findmydeviced": "Find My devices",
}
REVIEW = {
    "com.apple.Siri.agent": "reported Apple ID sign-in error in some configurations",
}
REVIEW_FRAGMENTS = (
    "icloud", "spotlight", "time", "backup", "findmy", "keychain",
    "continuity", "airdrop", "face", "imessage", "camera", "bluetooth",
    "power", "sleep", "battery", "update", "store", "network", "vpn",
    "siri", "notification",
)
LABEL = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$")


def parse_lines(content: str):
    labels = []
    problems = []
    for no, raw in enumerate(content.splitlines(), 1):
        s = raw.strip()
        if not s or s.startswith("#") or (s.startswith("[") and s.endswith("]")):
            continue
        label = s.split("#", 1)[0].strip()
        if not label:
            continue
        if not LABEL.fullmatch(label):
            problems.append(f"Line {no}: unexpected content; inspect manually: {label!r}")
        else:
            labels.append(label)
    return labels, problems


def audit(content: str):
    labels, parse_problems = parse_lines(content)
    critical, review = [], []
    for name in sorted(set(labels)):
        if name in CRITICAL:
            critical.append((name, CRITICAL[name]))
        elif name in REVIEW:
            review.append((name, REVIEW[name]))
        elif any(token in name.lower() for token in REVIEW_FRAGMENTS):
            review.append((name, "feature-dependent; manually review impact"))
    return labels, parse_problems, critical, review


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("preset", type=Path, help="plain-text label list generated by upstream --list")
    args = ap.parse_args()
    try:
        text = args.preset.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as exc:
        ap.error(str(exc))
    labels, problems, critical, review = audit(text)
    print(f"Audited {len(labels)} entries ({len(set(labels))} unique).")
    if len(set(labels)) != len(labels):
        print("WARNING: duplicate labels present.")
    for problem in problems:
        print(f"FORMAT WARNING: {problem}")
    for name, reason in critical:
        print(f"CRITICAL: {name} — {reason}")
    for name, reason in review:
        print(f"REVIEW: {name} — {reason}")
    if not labels:
        print("No service labels found.")
    print("No automated action taken; audit results never certify a preset as safe.")
    return 1 if (critical or problems or not labels) else 0


if __name__ == "__main__":
    raise SystemExit(main())
